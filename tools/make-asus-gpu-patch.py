def topaz_final(name):
    """The file as the topaz series leaves it."""
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run(['git', 'init', '-q', tmp], check=True)
        for p in sorted((repo / 'xnu/patches').glob('09[0-5]*.patch')):
            data = p.read_bytes().replace(b'\r\n', b'\n')      # (a Windows checkout may have CRLF)
            if ('+++ b/' + name).encode() not in data:
                continue
            lf = Path(tmp) / 'in.patch'
            lf.write_bytes(data)
            subprocess.run(['git', '-C', tmp, 'apply', '--include=' + name, str(lf)], check=True)
        # (git apply writes CRLF where core.autocrlf is on)
        return (Path(tmp) / name).read_bytes().replace(b'\r\n', b'\n').decode('latin-1')


def created(patch, name):
    """A file a patch creates in full (@@ -0,0 +1,N @@)."""
    lines = (repo / 'xnu/asus' / patch).read_bytes().replace(b'\r\n', b'\n').split(b'\n')
    at = lines.index(b'+++ b/' + name.encode())
    n = int(re.fullmatch(rb'@@ -0,0 \+1,(\d+) @@', lines[at + 1]).group(1))
    body = lines[at + 2:at + 2 + n]
    assert all(l.startswith(b'+') for l in body), name
    return b'\n'.join(l[1:] for l in body).decode('latin-1') + '\n'


def once(text, old, new):
    assert text.count(old) == 1, (text.count(old), old[:70])
    return text.replace(old, new)


def diff(name, before, after):
    assert before != after, name
    out = ''.join(difflib.unified_diff(before.splitlines(True), after.splitlines(True), 'a/' + name, 'b/' + name, n=3))
    return 'diff --git a/%s b/%s\n' % (name, name) + out


